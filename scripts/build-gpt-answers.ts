// Bundles content/gpt-answers/<slug>/<id>.md into one generated module so the
// server can serve them without filesystem reads at runtime.
// Run: npm run gpt-answers
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const SRC = join(process.cwd(), 'content', 'gpt-answers');
const OUT = join(process.cwd(), 'lib', 'interview-bank', 'gpt-answers.generated.ts');

const entries: [string, string][] = [];
if (existsSync(SRC)) {
  for (const slug of readdirSync(SRC).sort()) {
    const dir = join(SRC, slug);
    for (const file of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
      const md = readFileSync(join(dir, file), 'utf8').replace(/\r\n/g, '\n').trim();
      entries.push([`bank:${slug}/${file.slice(0, -3)}`, md]);
    }
  }
}

const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(
  OUT,
  `// GENERATED by scripts/build-gpt-answers.ts from content/gpt-answers — do not edit by hand.\n` +
    `export const GPT_ANSWERS: Record<string, string> = {\n${body}\n};\n`
);
console.log(`Wrote ${entries.length} answers to ${OUT}`);
